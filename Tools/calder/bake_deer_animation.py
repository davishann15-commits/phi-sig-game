"""Bake acquired animation into static 21-control tables; run in Blender."""
import bpy,hashlib,json,math
from pathlib import Path
from mathutils import Matrix,Vector

ROOT=Path(__file__).resolve().parents[2]
WORK=ROOT/'Saved/CalderWork/wildlife_revision_20261018_v1'
OUT=ROOT/'SourceArt/CalderLandscape/phase3/deer/animation'
OUT.mkdir(parents=True,exist_ok=True)
anatomy=json.loads((OUT.parent/'anatomy.json').read_text())
names=['Spine1','Neck','Neck1','Neck2']
for side,front in [('R',True),('L',True),('R',False),('L',False)]:
    names.extend([side+' '+('UpperArm' if front else 'Thigh'),side+' '+('Forearm' if front else 'Calf'),side+' '+('Hand' if front else 'HorseLink'),side+' '+('Finger0' if front else 'Foot')])
names+=['Head']
C=Matrix(((0,-100,0,0),(100,0,0,0),(0,0,100,.08724985),(0,0,0,1)))
rows=[];tables=[]
for name in ['Walk','Run','IdleGraze','IdleLookAround','IdleBreathe']:
    bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
    source=WORK/'animation_exports_v2'/(name+'.fbx')
    bpy.ops.import_scene.fbx(filepath=str(source))
    rig=next(o for o in bpy.context.scene.objects if o.type=='ARMATURE')
    action=rig.animation_data.action;start,end=action.frame_range
    duration=(end-start)/bpy.context.scene.render.fps
    count=math.ceil(duration*60);frames=[];feet=[[] for _ in range(4)]
    M=C@rig.matrix_world;inv=M.inverted()
    for i in range(count+1):
        frame=start+(end-start)*i/count;bpy.context.scene.frame_set(math.floor(frame),subframe=frame%1)
        row=[]
        for bone in names:
            b='DeerDoe_ '+bone
            delta=M@rig.pose.bones[b].matrix@rig.data.bones[b].matrix_local.inverted()@inv
            t,q,s=delta.decompose();assert max(abs(v-1) for v in s)<.004,(name,b,list(s))
            row.append([q.x,q.y,q.z,q.w,t.x,t.y,t.z])
        frames.append(row)
        for leg in range(4):
            j=7+4*leg;b='DeerDoe_ '+names[j]
            p=M@rig.pose.bones[b].matrix@rig.data.bones[b].matrix_local.inverted()@inv@Vector(anatomy['hooves_cm'][leg])
            feet[leg].append(list(p))
    phases=[];stances=[];strides=[];floors=[]
    for leg,curve in enumerate(feet):
        floor=min(p[2] for p in curve);floors.append(floor)
        grounded=[p[2]<floor+2.5 for p in curve[:-1]]
        best=(0,0);run=0
        for k in range(count*2):
            run=min(count,run+1) if grounded[k%count] else 0
            if run>best[1]:best=((k-run+1)%count,run)
        touch=best[0]/count;stance=max(.12,min(.82,best[1]/count));phases.append(touch);stances.append(stance)
        a=curve[best[0]];b=curve[(best[0]+max(1,best[1]-1))%count]
        strides.append(abs(b[0]-a[0])/max(.12,stance))
    stride=max(60.,min(450.,sum(strides)/4.))
    rows.append({'clip':name,'duration':duration,'samples':count+1,'stride_cm':stride,'touch_phase':phases,'stance_fraction':stances,'sole_floor_cm':floors,'fbx_sha256':hashlib.sha256(source.read_bytes()).hexdigest()})
    tables.append(frames)
    print('DEER_BAKE_CLIP',json.dumps(rows[-1]),flush=True)

header='// Generated by Tools/calder/bake_deer_animation.py from acquired Fab clips.\n// Numeric poses only: no runtime animation assets, skeletons or skeletal components.\nnamespace HouseCalderDeerAnimation {\n'
for k,frames in enumerate(tables):
    header+='static const float Clip%d[][21][7]={\n'%k
    for frame in frames:header+='{'+','.join('{'+','.join('%.7ff'%x for x in joint)+'}' for joint in frame)+'},\n'
    header+='};\n'
header+='inline int32 Frames(int32 Clip){static const int32 N[]={'+','.join(str(len(t)) for t in tables)+'};return N[Clip];}\n'
for fn,key in [('Duration','duration'),('Stride','stride_cm')]:
    header+='inline double '+fn+'(int32 Clip){static const double A[]={'+','.join('%.9f'%r[key] for r in rows)+'};return A[Clip];}\n'
for fn,key in [('Touch','touch_phase'),('Stance','stance_fraction'),('Floor','sole_floor_cm')]:
    header+='inline double '+fn+'(int32 Clip,int32 Leg){static const double A[][4]={'+','.join('{'+','.join('%.9f'%x for x in r[key])+'}' for r in rows)+'};return A[Clip][Leg];}\n'
header+='''inline FTransform Sample(int32 Clip,double Phase,int32 Joint)
{
    Phase=FMath::Fmod(FMath::Fmod(Phase,1.)+1.,1.);const double Frame=Phase*(Frames(Clip)-1);const int32 A=FMath::FloorToInt(Frame),B=FMath::Min(A+1,Frames(Clip)-1);
    const float (*Data)[21][7]=Clip==0?Clip0:Clip==1?Clip1:Clip==2?Clip2:Clip==3?Clip3:Clip4;
    auto Pose=[&](int32 I){const float* P=Data[I][Joint];return FTransform(FQuat(P[0],P[1],P[2],P[3]).GetNormalized(),FVector(P[4],P[5],P[6]));};
    FTransform Out;Out.Blend(Pose(A),Pose(B),float(Frame-A));return Out;
}
}
'''
target=ROOT/'Source/SeniorSendoff/HouseCalderDeerAnimation.inl';target.unlink(missing_ok=True);target.write_text(header)
(OUT/'bake.json').write_text(json.dumps({'clips':rows,'controls':names,'runtime_skeletons':0,'sample_rate':60},indent=2)+'\n')
